-- Real drag state machine, entirely mocked desktop/events/clock.
local mock=dofile('tests/support/mock_desktop.lua')
local passed,failed=0,0
local function test(name,fn)
 local ok,err=pcall(fn)
 if ok then passed=passed+1;print('PASS '..name)
 else failed=failed+1;print('FAIL '..name..': '..tostring(err))end
end
local function start(options)
 options=options or{}; options.realDrag=true
 local e=mock.environment(options);local w=e:window(1,false);e.focused=w
 assert(e.wm.dispatch('fullspan',w));return e,w,package.loaded.window_span_drag
end
test('stable pointer completes a real span in under 0.25 simulated seconds',function()
 local e,w,drag=start({requiredHoverTime=.05});e:advance(.25)
 assert(drag.lastRun and drag.lastRun.ok,'resize not completed')
 assert(w:frame().h>2100 and drag.lastRun.duration<.25)
 assert(drag.lastRun.dragEvents==2 and drag.lastRun.rehoverCount==0)
 mock.equalFrame(e.wm._savedFrames[1].frame,{x=0,y=0,w=1920,h=1080});e:close()
end)
test('mouse-down still waits for our tagged hover acknowledgement',function()
 local e,w,drag=start({deferOwnMove=true});e:advance(.2)
 assert(e.queuedMove and not e.dragStart)
 e:deliver(e.queuedMove);e:advance(.25)
 assert(drag.lastRun.ok);e:close()
end)
test('resize waits for mouse-down acknowledgement',function()
 local e,w,drag=start({deferOwnDown=true});e:advance(.25)
 assert(e.queuedDown and w:frame().h==1080)
 e:acknowledgeDown();e:advance(.25);assert(drag.lastRun.ok);e:close()
end)
test('missing acknowledgement fails without leaving a button held',function()
 local e,w,drag=start({deferOwnDown=true});e:advance(1.5)
 assert(drag.lastRun and not drag.lastRun.ok and drag.lastRun.dragEvents==0)
 assert(e.mouseEvents[#e.mouseEvents]=='up');e:close()
end)
test('stationary hover feedback cannot restart the quiet period',function()
 local e,w,drag=start();e:advance(.045)
 local p=e.mouse; e:sendMouse('move',p);e:advance(.205)
 assert(drag.lastRun.ok and not drag.lastRun.restorationUnsafe);e:close()
end)
test('real pointer motion during resize cancels and releases',function()
 local e,w,drag=start();e:advance(.11)
 assert(e.wm._pendingSpan and e.wm._pendingSpan.controller.isDragging())
 e:sendMouse('move',{x=800,y=700});e:advance(.2)
 assert(not drag.lastRun.ok and drag.lastRun.reason=='user-interrupted')
 assert(e.mouseEvents[#e.mouseEvents]=='up');assert(e.mouse.x==800 and e.mouse.y==700);e:close()
end)
test('a held modifier delays resizing until it is released',function()
 local e,w,drag=start();e.flags={cmd=true};e:advance(.3)
 assert(#e.mouseEvents==0);e.flags={};e:advance(.3);assert(drag.lastRun.ok);e:close()
end)
test('desktop presentation changes prevent mouse-down',function()
 local e,w,drag=start();e:advance(.04);e.cgMissing=true;e:advance(.3)
 assert(not drag.lastRun.ok and not e.dragStart);e:close()
end)
test('faster verification still rejects an unchanged single-screen window',function()
 local e,w,drag=start({requiredHoverTime=10});e:advance(.6)
 assert(not drag.lastRun.ok and w:frame().h<=1080);e:close()
end)
test('repeat A while resizing joins the operation',function()
 local e,w,drag=start();e:advance(.11);assert(e.wm.dispatch('fullspan',w));e:advance(.3)
 assert(drag.lastRun.ok and w:frame().h>2100);e:close()
end)
print(string.format('%d passed, %d failed',passed,failed))
assert(failed==0,'span drag regression')
