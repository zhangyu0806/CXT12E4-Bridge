-- Regression for app tab navigation versus deliberate manual window edits.
local mock = dofile("tests/support/mock_desktop.lua")
local passed, failed = 0, 0
local function test(name, fn)
  local ok, err = pcall(fn)
  if ok then passed=passed+1; print('PASS '..name)
  else failed=failed+1; print('FAIL '..name..': '..tostring(err)) end
end
local function spanning(bundle, options)
  local e=mock.environment(options)
  local w=e:window(1,true,{x=0,y=0,w=1920,h=2158})
  w.bundleID=bundle or 'notion.id'; e.focused=w
  return e,w
end
local function clamp(e,w)
  w.frameValue={x=0,y=0,w=1920,h=1080}; e:emit(w,'title'); e:emit(w,'moved')
end
local function kept(e,w)
  assert(e.members[w:id()], 'tab navigation removed span membership')
  assert(w:frame().h>2100, 'window did not recover both screens')
  assert(not e.wm._savedFrames[w:id()].maintenanceDisabled)
  mock.equalFrame(e.wm._savedFrames[w:id()].frame,{x=100,y=100,w=800,h=600})
end
for _,bundle in ipairs({'notion.id','com.openai.codex','md.obsidian'}) do
  test(bundle..' mouse tab click keeps span and original restore frame',function()
    local e,w=spanning(bundle)
    e:sendMouse('down',{x=250,y=18}); clamp(e,w)
    e:sendMouse('up',{x=250,y=18}); e:advance(1)
    kept(e,w)
    assert(e.wm.dispatch('fullspan',w)); e:advance(.5)
    mock.equalFrame(w:frame(),{x=100,y=100,w=800,h=600})
    assert(not e.members[1]); e:close()
  end)
end
test('slight mouse jitter during a tab click does not disable span',function()
  local e,w=spanning(); e:sendMouse('down',{x=250,y=18})
  e:sendMouse('drag',{x=251,y=19}); clamp(e,w); e:sendMouse('up'); e:advance(1)
  kept(e,w); e:close()
end)
test('delayed tab clamp after mouse-up still repairs',function()
  local e,w=spanning(); e:sendMouse('down'); e:sendMouse('up'); e:advance(.2)
  clamp(e,w); e:advance(1); kept(e,w); e:close()
end)
test('rapid next tab click keeps its own gesture until mouse-up',function()
  local e,w=spanning(); e:sendMouse('down'); e:sendMouse('up'); e:advance(.05)
  e:sendMouse('down',{x=450,y=18}); clamp(e,w); e:advance(.3)
  assert(e.wm._userGesture and #e.calls==0)
  e:sendMouse('up'); e:advance(1); kept(e,w); e:close()
end)
test('mouse drift without a dragged event is still a click',function()
  local e,w=spanning(); e:sendMouse('down',{x=250,y=18})
  e:sendMouse('move',{x=260,y=18}); clamp(e,w); e:sendMouse('up'); e:advance(1)
  kept(e,w); e:close()
end)
test('keyboard tab navigation needs no mouse gesture',function()
  local e,w=spanning(); clamp(e,w); e:advance(1); kept(e,w); e:close()
end)
test('real resize to exactly one screen stays manual',function()
  local e,w=spanning(); e:sendMouse('down',{x=960,y=2157})
  e:sendMouse('drag',{x=960,y=1079}); clamp(e,w); e:sendMouse('up'); e:advance(2)
  assert(not e.members[1]); assert(e.wm._savedFrames[1].maintenanceDisabled)
  assert(w:frame().h==1080 and #e.calls==0); e:close()
end)
test('deliberate title-bar double click opts out when frame changes',function()
  local e,w=spanning()
  local event=hs.eventtap.event.newMouseEvent('down',{x=1000,y=18})
  event:setProperty(hs.eventtap.event.properties.mouseEventClickState,2); e:deliver(event)
  clamp(e,w); e:sendMouse('up'); e:advance(1)
  assert(not e.members[1] and #e.calls==0); e:close()
end)
test('ordinary unregistered windows are never enrolled by tab clicks',function()
  local e=mock.environment(); local w=e:window(1,false); e.focused=w
  e:sendMouse('down'); clamp(e,w); e:sendMouse('up'); e:advance(2)
  assert(not e.members[1] and #e.calls==0); e:close()
end)
test('explicit half-screen shortcut ends span maintenance',function()
  local e,w=spanning(); assert(e.wm.dispatch('left',w)); e:advance(1)
  assert(not e.members[1] and #e.calls==0); assert(w:frame().w==960); e:close()
end)
test('mouse button held during tab navigation prevents automatic resize',function()
  local e,w=spanning(); e.buttons={left=true}; e:sendMouse('down'); clamp(e,w); e:advance(1)
  assert(#e.calls==0 and e.members[1]); e.buttons={}; e:sendMouse('up'); e:advance(1)
  kept(e,w); e:close()
end)
print(string.format('%d passed, %d failed',passed,failed))
assert(failed==0,'span tab regression')
