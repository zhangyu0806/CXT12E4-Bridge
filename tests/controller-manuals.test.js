#!/usr/bin/env node
'use strict';

// Read-only documentation checks: no browser, input injection, HID or network.
// Generate both exports from the current builds before running this test. The
// JSON files are inputs, not committed fixtures or proof of hardware acceptance.
//
// From the repository root:
//   Cxt12E4Bridge.exe --dump-default-profiles > outputs/windows-default-profiles.json
//   "outputs/CXT12E4 Bridge.app/Contents/MacOS/CXT12E4Bridge" --dump-default-profiles > outputs/mac-default-profiles.json
//   node tests/controller-manuals.test.js outputs/windows-default-profiles.json outputs/mac-default-profiles.json
//
// Windows PowerShell 5 users should use `| Set-Content -Encoding UTF8 PATH`.
// A Mac-hosted Windows export can alternatively be generated by the actual C#
// source through install/windows-home/test-portable.py --export-defaults PATH;
// that harness uses a test-only JSON adapter, not the Windows serializer.

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ROOT = path.resolve(__dirname, '..');

function usage() {
  return [
    'Usage: node tests/controller-manuals.test.js WINDOWS_EXPORT.json MAC_EXPORT.json',
    '       node tests/controller-manuals.test.js --windows PATH --mac PATH',
    '',
    'Both arguments must be fresh --dump-default-profiles exports from the current builds.',
    'Paths are resolved against the invoking working directory; repository HTML is found relative to this script.',
    'Example output names: outputs/windows-default-profiles.json and outputs/mac-default-profiles.json.',
    'No export paths supplied means no mapping checks are run; this is an error, not a passing test.',
    'See the script header for export commands. DOM checks are not native-browser or hardware acceptance.'
  ].join('\n');
}

function exportPaths(args) {
  if (args.length === 1 && ['--help', '-h'].includes(args[0])) {
    console.log(usage());
    process.exit(0);
  }
  if (args.length === 2 && args.every(value => !value.startsWith('--'))) {
    return { windows: path.resolve(args[0]), mac: path.resolve(args[1]) };
  }
  const result = {};
  for (let index = 0; index < args.length; index += 2) {
    const option = args[index];
    const value = args[index + 1];
    if (!['--windows', '--mac'].includes(option) || !value || value.startsWith('--') || result[option.slice(2)]) {
      throw new Error('Invalid or duplicate export argument.\n' + usage());
    }
    result[option.slice(2)] = path.resolve(value);
  }
  if (!result.windows || !result.mac) throw new Error('Missing Windows and/or Mac CLI export path.\n' + usage());
  return result;
}

function readExport(filename, platform) {
  if (!fs.existsSync(filename)) throw new Error(platform + ' export does not exist: ' + filename + '\nGenerate it from the current build before running the check.');
  const bytes = fs.readFileSync(filename);
  const encoding = bytes[0] === 0xff && bytes[1] === 0xfe ? 'utf16le' : 'utf8';
  const layers = JSON.parse(bytes.toString(encoding).replace(/^\uFEFF/, ''));
  assert(Array.isArray(layers), platform + ' export must be an array');
  assert.equal(layers.length, 8, platform + ' export must contain eight layers');
  assert.deepEqual(layers.map(layer => layer.layer).sort((a, b) => a - b), [1, 2, 3, 4, 5, 6, 7, 8]);
  return layers;
}

// The Mac manual specializes generic navigation titles. These are editorial
// labels, not an alternative device mapping: every underlying action ID still
// has to match the live CLI export below. Native shortcut semantics require the
// application/device acceptance described in the manual.
const MAC_NAVIGATION_TITLES = {
  1: ['上一个 Codex 任务', '下一个 Codex 任务'],
  2: ['上一个 tmux window', '下一个 tmux window'],
  3: ['页面后退', '页面前进'],
  4: ['上一个标签', '下一个标签'],
  5: ['视角向左旋转', '视角向右旋转'],
  6: ['上一个 Finder 标签', '下一个 Finder 标签'],
  7: ['上一会话', '下一会话'],
  8: ['上一个标签', '下一个标签']
};

// Minimal DOM required by these standalone manuals. This deliberately verifies
// behavior and element wiring without pretending to measure browser layout.
class Element {
  constructor(tag = 'div') {
    this.tagName = tag;
    this.children = [];
    this.dataset = {};
    this.attributes = {};
    this.style = { setProperty() {} };
    this.classList = { toggle() {}, add() {}, remove() {} };
    this.events = {};
    this.hidden = false;
    this.value = '';
  }
  append(...nodes) { this.children.push(...nodes); }
  replaceChildren(...nodes) { this.children = nodes; }
  addEventListener(name, callback) { this.events[name] = callback; }
  setAttribute(name, value) { this.attributes[name] = value; }
  hasAttribute(name) { return Object.hasOwn(this.attributes, name); }
  scrollIntoView() {}
  focus() {}
  select() {}
  blur() {}
}

function loadManual(platform) {
  const relative = platform === 'windows' ? 'docs/cxt12e4-manual/index.html' : 'docs/cxt12e4-manual/mac/index.html';
  const html = fs.readFileSync(path.join(ROOT, relative), 'utf8');
  const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
  assert.equal(scripts.length, 1, platform + ' manual must have one inline script');
  const source = scripts[0][1];
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  assert.equal(new Set(ids).size, ids.length, platform + ' HTML IDs are unique');
  const elements = Object.fromEntries(ids.map(id => [id, new Element()]));
  const devices = ['keyboard', 'xbox'].map(device => {
    const button = new Element('button'); button.dataset.device = device; return button;
  });
  const platformLinks = [...html.matchAll(/<a\b([^>]*data-manual-page="([^"]+)"[^>]*)>/g)].map(match => {
    const id = match[1].match(/\bid="([^"]+)"/);
    const link = id ? elements[id[1]] : new Element('a');
    link.dataset.manualPage = match[2];
    link.dataset.manualBase = match[1].match(/data-manual-base="([^"]+)"/)[1];
    return link;
  });
  const document = {
    body: { dataset: { manualPage: platform } },
    documentElement: new Element('html'),
    getElementById(id) { assert(elements[id], 'Missing HTML element: ' + id); return elements[id]; },
    querySelectorAll(selector) { if (selector === 'a[data-manual-page]') return platformLinks; assert.equal(selector, '[data-device]'); return devices; },
    createElement(tag) { return new Element(tag); },
    addEventListener() {}
  };
  const location = {
    href: 'http://localhost/' + (platform === 'mac' ? 'mac/' : '') + '?device=xbox&layer=0',
    search: '?device=xbox&layer=0'
  };
  const updateLocation = (_state, _title, url) => { location.href = String(url); location.search = new URL(url).search; };
  const history = { replaceState: updateLocation, pushState: updateLocation };
  const windowEvents = {};
  const window = { location, history, print() {}, addEventListener(name, callback) { windowEvents[name] = callback; } };
  const context = vm.createContext({ document, location, history, URL, URLSearchParams, window });
  new vm.Script(fs.readFileSync(path.join(ROOT, 'docs/cxt12e4-manual/manual-navigation.js'), 'utf8')).runInContext(context, { timeout: 1000 });
  new vm.Script(source, { filename: relative }).runInContext(context, { timeout: 1000 });
  const run = code => vm.runInContext(code, context, { timeout: 1000 });
  const profiles = JSON.parse(run('JSON.stringify(xboxProfiles)'));
  assert.deepEqual(Object.keys(profiles).sort(), ['1', '2', '3', '4', '5', '6', '7', '8']);
  assert.equal(run('current'), 8, 'Legacy layer=0 displays layer 8');
  return { elements, devices, location, profiles, run, windowEvents };
}

function compareMappings(platform, profiles, layers) {
  let comparisons = 0;
  for (const layer of layers) {
    const device = layer.devices.find(item => item.device === 'xbox');
    assert(device, platform + ' L' + layer.layer + ' Xbox export exists');
    assert.equal(device.controls.length, 26, 'Xbox export includes two sticks, twelve buttons and twelve RT combinations');
    const controls = Object.fromEntries(device.controls.map(control => [control.control, control]));
    assert.equal(Object.keys(controls).length, 26, 'Export controls are unique');
    const rows = profiles[layer.layer];
    assert.equal(rows.length, 14, 'Manual shows two sticks and twelve button rows');
    assert.equal(new Set(rows.map(row => row.control)).size, 14, 'Manual rows are unique');
    for (const row of rows) {
      const expected = controls[row.control];
      const context = platform + ' L' + layer.layer + ' ' + row.control;
      assert(expected, context + ' exists in export');
      assert(!row.control.startsWith('rt.'), context + ' must be a base control');
      assert.equal(row.action, expected.action, context + ' default action');
      assert.equal(row.label, expected.label, context + ' control label');
      const title = platform === 'mac' && ['lb', 'rb'].includes(row.control)
        ? MAC_NAVIGATION_TITLES[layer.layer][row.control === 'lb' ? 0 : 1] : expected.title;
      assert.equal(row.title, title, context + ' action title');
      comparisons++;
      const rt = controls['rt.' + row.control];
      assert.equal(row.rtAction, rt ? rt.action : 'none', context + ' RT action');
      assert.equal(row.rtTitle, !rt || rt.action === 'none' ? '—' : rt.title, context + ' RT action title');
      if (rt) comparisons++;
    }
  }
  return comparisons;
}

function checkRendering(manual) {
  const { elements, devices, location, run } = manual;
  let states = 0;
  for (let layer = 1; layer <= 8; layer++) {
    for (const device of ['keyboard', 'xbox']) {
      run(`currentDevice='${device}'; showLayer(${layer})`);
      assert.equal(elements.keyboardWorkspace.hidden, device !== 'keyboard');
      assert.equal(elements.xboxPanel.hidden, device !== 'xbox');
      assert.equal(elements.keyboardGrid.children.length, 12);
      assert.equal(elements.encoderList.children.length, 4);
      assert.equal(elements.xboxMappings.children.length, 14);
      assert.equal(new URL(location.href).searchParams.get('device'), device);
      assert.equal(new URL(location.href).searchParams.get('layer'), String(layer));
      assert(elements.otherPlatform.href.includes(`device=${device}&layer=${layer}`));
      assert.equal(devices.find(button => button.dataset.device === device).attributes['aria-pressed'], 'true');
      states++;
    }
  }
  elements.searchInput.value = '鼠标左键';
  run('search()');
  assert(elements.searchResults.children.length > 0, 'Xbox mappings can be searched');
  elements.searchResults.children[0].events.click();
  assert.equal(run('currentDevice'), 'xbox', 'Search switches to the matching device');
  location.href = 'http://localhost/?device=keyboard&layer=3'; location.search = '?device=keyboard&layer=3';
  manual.windowEvents.popstate();
  assert.equal(run('current'), 3, 'Back/forward re-renders the URL layer');
  assert.equal(run('currentDevice'), 'keyboard', 'Back/forward restores the device');
  assert.equal(elements.layerNav.children[2].attributes['aria-pressed'], 'true');
  assert.equal(elements.keyboardWorkspace.hidden, false);
  return states;
}

function checkWindowsDifferences(profiles) {
  const row = (layer, control) => profiles[layer].find(item => item.control === control);
  assert.equal(row(2, 'x').rtAction, 'button.10', 'Terminal RT+X enters copy-mode');
  assert.equal(row(2, 'y').rtAction, 'button.9', 'Terminal RT+Y stashes/restores input');
  assert.equal(row(6, 'l3').rtAction, 'files.open', 'Windows RT+L3 opens the selected TC item');
  assert.match(row(2, 'a').rtTitle, /Ctrl\+Shift\+C/, 'Terminal copy does not send Ctrl+C');
  assert.match(row(2, 'b').rtTitle, /Ctrl\+Shift\+V/);
}

function checkFaceButtonContract(platform, profiles) {
  const layerActions = {
    1: 'codex.composer', 2: 'button.5', 3: 'encoder.2.1', 4: 'button.2',
    5: 'button.1', 6: platform === 'mac' ? 'finder.open' : 'files.open',
    7: 'button.4', 8: 'button.9'
  };
  for (let layer = 1; layer <= 8; layer++) {
    const rows = Object.fromEntries(profiles[layer].map(row => [row.control, row]));
    for (const [control, action] of Object.entries({
      x: 'mouse.left', y: 'mouse.right', a: 'key.enter', b: 'key.escape'
    })) {
      assert.equal(rows[control].action, action, `${platform} L${layer} keeps ${control.toUpperCase()} consistent`);
    }
    assert.equal(rows.l3.action, 'bridge.help', `${platform} L${layer} plain L3 still opens settings`);
    assert.equal(rows.l3.rtAction, layerActions[layer], `${platform} L${layer} RT+L3 retains the layer-specific action`);
  }
}

function main() {
  const exports = exportPaths(process.argv.slice(2));
  let comparisons = 0;
  let states = 0;
  for (const platform of ['windows', 'mac']) {
    const layers = readExport(exports[platform], platform);
    const manual = loadManual(platform);
    comparisons += compareMappings(platform, manual.profiles, layers);
    states += checkRendering(manual);
    checkFaceButtonContract(platform, manual.profiles);
    if (platform === 'windows') checkWindowsDifferences(manual.profiles);
    console.log(`PASS ${platform}: 208 exported actions, 16 device/layer DOM states, labels, links, search, unique IDs and JS syntax.`);
  }
  assert.equal(comparisons, 416);
  assert.equal(states, 32);
  console.log('PASS 416 exported-action comparisons and 32 render states. DOM harness only; no browser layout, native input or hardware acceptance.');
}

try { main(); }
catch (error) { console.error('FAIL controller manuals: ' + error.message); process.exitCode = 1; }
