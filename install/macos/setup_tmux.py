#!/usr/bin/env python3
"""Install the versioned Mac tmux layer; plan by default, back up before applying."""
import argparse
import datetime
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TEMPLATES = ROOT / 'integrations/tmux/macos'
BEGIN = '# BEGIN CXT12E4 macOS tmux'
END = '# END CXT12E4 macOS tmux'


def quote(value):
    """tmux config string, without shell interpolation."""
    return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def managed_block(text, content):
    block = BEGIN + '\n' + content.rstrip() + '\n' + END
    if BEGIN in text or END in text:
        if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
            raise ValueError('Malformed CXT12E4 managed block; review it before installing')
        return re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    return text.rstrip() + ('\n\n' if text.strip() else '') + block + '\n'


def find_executable(candidates, probe=None):
    for candidate in candidates:
        found = shutil.which(str(candidate))
        if found and (probe is None or probe(found)):
            return str(Path(found).absolute())
    raise RuntimeError('Required executable unavailable: ' + ', '.join(map(str, candidates)))


def dependencies(home):
    brew = find_executable(['/opt/homebrew/bin/brew', '/usr/local/bin/brew', 'brew'])
    prefix = Path(subprocess.check_output([brew, '--prefix'], text=True).strip())
    def version_ok(path, args, minimum):
        try:
            value = subprocess.check_output([path, *args], text=True, stderr=subprocess.DEVNULL).strip()
            return tuple(map(int, value.split('.')[:2])) >= minimum
        except (OSError, ValueError, subprocess.SubprocessError):
            return False
    bash = find_executable([prefix/'bin/bash', 'bash'], lambda p: version_ok(p, ['-c', 'printf "%s" "$BASH_VERSION"'], (4, 0)))
    python = find_executable([home/'.local/bin/python3.12', prefix/'bin/python3', 'python3'],
                             lambda p: version_ok(p, ['-c', 'import sys; print("%s.%s" % sys.version_info[:2])'], (3, 10)))
    tmux = find_executable([home/'.local/bin/tmux', prefix/'bin/tmux', 'tmux'])
    find_executable([prefix/'bin/fzf', 'fzf'])
    for package, command in [('coreutils', 'stat'), ('findutils', 'find')]:
        path = prefix/'opt'/package/'libexec/gnubin'/command
        if not path.is_file():
            raise RuntimeError('Missing GNU tools; run brew install bash python tmux coreutils findutils fzf')
    for plugin in ('tpm/tpm', 'tmux-resurrect/scripts/save.sh', 'tmux-resurrect/save_command_strategies/ps.sh', 'tmux-continuum/continuum.tmux'):
        if not (home/'.tmux/plugins'/plugin).is_file():
            raise RuntimeError('Pinned tmux plugins are missing; run bash /path/to/winsettings/tmux/install.sh --apply --plugins, then retry')
    return {'bash': bash, 'python': python, 'tmux': tmux, 'brew_prefix': str(prefix)}


def resolve_winsettings(home, requested=None):
    candidates = [Path(requested).expanduser()] if requested else [home/'.config/tmux/winsettings', home/'code/winsettings', home/'winsettings']
    for path in candidates:
        data = path/'tmux' if (path/'tmux/tmux.conf').is_file() else path
        if all((data/name).is_file() for name in ('tmux.conf', 'shared.conf', 'profiles/portable.conf')):
            return data.resolve()
    raise FileNotFoundError('winsettings not found. Clone it first, then run setup_tmux.py --apply --winsettings /path/to/winsettings')


def render_config(home, source, deps, inherited_path):
    base = home/'.config/tmux'
    prefix = Path(deps['brew_prefix'])
    paths = [str(base/'macos-bin'), str(Path(deps['bash']).parent), str(Path(deps['tmux']).parent),
             str(prefix/'bin'), str(prefix/'opt/coreutils/libexec/gnubin'), str(prefix/'opt/findutils/libexec/gnubin'),
             str(home/'.local/bin'), *inherited_path.split(':')]
    path = ':'.join(dict.fromkeys(p for p in paths if p))
    lifecycle = shlex.join([deps['python'], str(base/'macos/pane-lifecycle.py'), '--tmux', deps['tmux']])
    lifecycle += ' --socket #{q:socket_path} --server-pid #{pid}'
    lines = ['# Generated by CXT12E4 install/macos/setup_tmux.py; source after local preferences.',
             'set -g @cxt-macos-integration "1"',
             'set -s default-client-command attach-session',
             'set-environment -g PATH ' + quote(path), 'set-environment -g PYTHONDONTWRITEBYTECODE "1"',
             'set -g default-shell /bin/zsh',
             'source-file ' + quote(base/'winsettings/shared.conf'), 'source-file ' + quote(base/'winsettings/profiles/portable.conf'),
             'source-file ' + quote(base/'macos-keys.conf'),
             'set-hook -g "pane-died[80]" ' + quote('run-shell -b ' + quote(lifecycle + ' recover #{pane_id}')),
             'bind-key -T prefix R run-shell ' + quote(lifecycle + ' restart #{pane_id}'),
             '# Explicit process allowlist; no automatic startup/restore or cross-machine publication.',
             'set -g @resurrect-processes "claude opencode grok"',
             'set -g @resurrect-save-command-strategy "cxt-macos"',
             *['set -g @resurrect-strategy-' + agent + ' "cxt-macos"' for agent in ('claude', 'opencode', 'grok')],
             'set -g @continuum-restore "off"', 'set -g @continuum-boot "off"',
             'if-shell ' + quote('test -f ' + shlex.quote(str(home/'.tmux/plugins/tpm/tpm'))) +
             ' ' + quote('run-shell ' + quote(str(home/'.tmux/plugins/tpm/tpm')))]
    return '\n'.join(lines) + '\n'


def plan(home, source, deps, inherited_path):
    source = source.resolve()
    base = home/'.config/tmux'
    files = {}
    links = {}
    compat = base/'winsettings'
    if compat.exists() or compat.is_symlink():
        if compat.resolve() != source:
            raise RuntimeError('Existing winsettings link points elsewhere; use its current release or migrate with winsettings settingsctl first')
    else:
        links[compat] = source
    entry = home/'.tmux.conf'
    if entry.exists() or entry.is_symlink():
        direct_local = False
        if entry.exists():
            for line in entry.read_text().splitlines():
                try:
                    words = shlex.split(line, comments=True)
                except ValueError:
                    continue
                if len(words) in (2, 3) and words[0] in ('source', 'source-file') and (len(words) == 2 or words[1] == '-q'):
                    target = words[-1]
                    if target.startswith('~/'):
                        target = str(home/target[2:])
                    elif target.startswith('$HOME/'):
                        target = str(home/target[6:])
                    direct_local = direct_local or Path(target) == base/'local.conf'
        if not entry.exists() or not (entry.resolve() == source/'tmux.conf' or direct_local):
            raise RuntimeError('Existing tmux entry does not load local.conf; preserve it and integrate the Mac layer explicitly')
    elif (home/'.local/state/winsettings/journal/tmux.log').exists():
        raise RuntimeError('winsettings owns this entry; repair it with settingsctl before installing the Mac layer')
    else:
        links[entry] = source/'tmux.conf'
    for name in ('pane-lifecycle.py', 'darwin-process.py', 'resurrect-command.py', 'resurrect-restore.py'):
        files[base/'macos'/name] = (TEMPLATES/name).read_bytes()
    files[base/'macos-keys.conf'] = (TEMPLATES/'keys.conf').read_bytes()
    files[base/'macos/macos.conf'] = render_config(home, source, deps, inherited_path).encode()
    for name in ('ps', 'pgrep'):
        command = shlex.join([deps['python'], str(base/'macos/darwin-process.py'), name])
        files[base/'macos-bin'/name] = ('#!/bin/sh\nexec ' + command + ' "$@"\n').encode()
    files[base/'macos-bin/python3'] = ('#!/bin/sh\nexec ' + shlex.quote(deps['python']) + ' "$@"\n').encode()
    strategies = home/'.tmux/plugins/tmux-resurrect/save_command_strategies'
    save_command = shlex.join([deps['python'], str(base/'macos/resurrect-command.py'), '--tmux', deps['tmux'],
                              '--fallback', str(strategies/'ps.sh'), '--bash', deps['bash']])
    files[strategies/'cxt-macos.sh'] = ('#!/bin/sh\nexec ' + save_command + ' "$@"\n').encode()
    restore_command = shlex.join([deps['python'], str(base/'macos/resurrect-restore.py'), '--tmux', deps['tmux'],
                                 '--python', deps['python'], '--lifecycle', str(base/'macos/pane-lifecycle.py')])
    for agent in ('claude', 'opencode', 'grok'):
        files[home/'.tmux/plugins/tmux-resurrect/strategies'/(agent+'_cxt-macos.sh')] = (
            '#!/bin/sh\nexec ' + restore_command + ' "$@"\n').encode()
    local = base/'local.conf'
    text = local.read_text() if local.exists() else ''
    files[local] = managed_block(text, 'source-file ' + quote(base/'macos/macos.conf')).encode()
    ghostty = home/'Library/Application Support/com.mitchellh.ghostty/config.ghostty'
    old = ghostty.read_text() if ghostty.exists() else ''
    files[ghostty] = managed_block(old, 'macos-option-as-alt = true\nkeybind = alt+arrow_left=unbind\nkeybind = alt+arrow_right=unbind').encode()
    return files, links


def apply_plan(home, files, links):
    backup = home/'.local/state/tmux-macos-backups'/datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f-setup')
    changed = []
    for path, value in {**files, **links}.items():
        same = path.is_symlink() and path.resolve() == value if path in links else path.is_file() and not path.is_symlink() and path.read_bytes() == value
        if same:
            continue
        if path.exists() or path.is_symlink():
            dest = backup/path.relative_to(home)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dest, follow_symlinks=False)
        path.parent.mkdir(parents=True, exist_ok=True)
        temp = path.with_name(path.name + f'.cxt-{os.getpid()}.tmp')
        if path in links:
            temp.symlink_to(value)
        else:
            temp.write_bytes(value)
            temp.chmod(0o755 if path.parent.name in ('macos-bin', 'save_command_strategies', 'strategies') else 0o600)
        temp.replace(path)
        changed.append(str(path))
    if changed:
        backup.mkdir(parents=True, exist_ok=True)
        (backup/'changes.json').write_text(json.dumps({'changed': changed}, indent=2))
    return changed, backup


def reload_running(home, deps):
    def tm(*args):
        return subprocess.run([deps['tmux'], *args], capture_output=True, text=True, timeout=20)
    before = tm('list-panes', '-a', '-F', '#{pane_id} #{pane_pid}')
    if before.returncode:
        print('No running tmux server; the configuration will load at the next start.')
        return
    identity = tm('display-message', '-p', '#{socket_path}\t#{pid}')
    if identity.returncode:
        raise RuntimeError(identity.stderr.strip())
    socket, pid = identity.stdout.strip().split('\t')
    script = str(home/'.config/tmux/macos/pane-lifecycle.py')
    subprocess.run([deps['python'], script, '--tmux', deps['tmux'], '--socket', socket, '--server-pid', pid, 'remember', '--all'], check=True)
    tm('set-option', '-gu', '@cxt-macos-integration')
    result = tm('source-file', str(home/'.tmux.conf'))
    if result.returncode:
        raise RuntimeError(result.stderr.strip())
    if tm('show-options', '-gqv', '@cxt-macos-integration').stdout.strip() != '1':
        raise RuntimeError('The tmux entry did not load the Mac integration')
    after = tm('list-panes', '-a', '-F', '#{pane_id} #{pane_pid}')
    if before.stdout != after.stdout:
        raise RuntimeError('Pane inventory changed during reload; inspect it before continuing')
    print('tmux reloaded; existing pane IDs and process IDs preserved.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true', help='Write the plan with timestamped backups')
    parser.add_argument('--reload', action='store_true', help='After apply, remember existing Agent commands and reload tmux without restarting panes')
    parser.add_argument('--winsettings', help='winsettings checkout, or its tmux directory/current immutable release')
    parser.add_argument('--if-configured', action='store_true', help='Skip with a notice if no existing winsettings tree is present')
    args = parser.parse_args()
    if sys.platform != 'darwin':
        raise RuntimeError('This installer is for macOS')
    home = Path.home()
    try:
        source = resolve_winsettings(home, args.winsettings)
    except FileNotFoundError as error:
        if args.if_configured:
            print('tmux setup skipped:', error)
            return
        raise
    deps = dependencies(home)
    inherited_path = os.environ.get('PATH', '/usr/bin:/bin')
    previous = subprocess.run([deps['tmux'], '-N', 'show-environment', '-g', 'PATH'], capture_output=True, text=True)
    if previous.returncode == 0 and previous.stdout.startswith('PATH='):
        inherited_path = previous.stdout.strip()[5:] + ':' + inherited_path
    files, links = plan(home, source, deps, inherited_path)
    print('winsettings:', source)
    print('Mac layer:', home/'.config/tmux/macos/macos.conf')
    if not args.apply:
        print('Dry run; rerun with --apply --reload to install and load the Mac layer.')
        return
    changed, backup = apply_plan(home, files, links)
    print('Changed files:', len(changed))
    if changed:
        print('Backups:', backup)
    if args.reload:
        reload_running(home, deps)


if __name__ == '__main__':
    try:
        main()
    except (OSError, RuntimeError, ValueError, subprocess.SubprocessError) as error:
        print('tmux setup:', error, file=sys.stderr)
        sys.exit(1)
